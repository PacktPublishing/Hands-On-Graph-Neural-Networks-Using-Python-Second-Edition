def next_node(G, previous, current, p, q):
    neighbors = list(G.neighbors(current))
    alphas = []
    for neighbor in neighbors:
        if neighbor == previous:
            alpha = 1 / p
        elif previous is not None and G.has_edge(neighbor, previous):
            alpha = 1
        else:
            alpha = 1 / q
        alphas.append(alpha * G[current][neighbor].get('weight', 1))
    probs = [a / sum(alphas) for a in alphas]
    next_node_id = np.random.choice(neighbors, size=1, p=probs)[0]
    return next_node_id


def random_walk(G, start, length, p, q):
    walk = [start]
    for _ in range(length):
        current = walk[-1]
        previous = walk[-2] if len(walk) > 1 else None
        neighbors = list(G.neighbors(current))
        if not neighbors:
            break
        walk.append(next_node(G, previous, current, p, q))
    return [str(x) for x in walk]


