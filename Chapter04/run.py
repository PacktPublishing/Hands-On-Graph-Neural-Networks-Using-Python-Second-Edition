def train_node2vec(G, p, q, walks_per_node=80, length=10, context_size=10,
                   dim=128, epochs=5, seed=0):
    np.random.seed(seed)
    torch.manual_seed(seed)

    walks = [random_walk(G, node, length, p, q)
             for _ in range(walks_per_node) for node in G.nodes]
    node_idx = {str(node): i for i, node in enumerate(G.nodes)}
    walks = torch.tensor([[node_idx[n] for n in walk] for walk in walks])
    pos_rw = walks.unfold(1, context_size, 1).reshape(-1, context_size)

    model = Node2Vec(from_networkx(G).edge_index, embedding_dim=dim,
                     walk_length=length, context_size=context_size,
                     sparse=True)
    with torch.no_grad():
        model.embedding.weight.uniform_(-0.5 / dim, 0.5 / dim)
    optimizer = torch.optim.SparseAdam(model.parameters(), lr=0.01)

    num_nodes = G.number_of_nodes()
    for _ in range(epochs):
        for batch in torch.randperm(pos_rw.size(0)).split(512):
            pos = pos_rw[batch]
            neg = torch.cat([
                pos[:, :1].repeat(5, 1),
                torch.randint(num_nodes, (pos.size(0) * 5, context_size - 1)),
            ], dim=1)
            optimizer.zero_grad()
            loss = model.loss(pos, neg)
            loss.backward()
            optimizer.step()

    return model().detach().numpy()


def evaluate(embeddings, labels, n_runs=10):
    accs = []
    for seed in range(n_runs):
        X_tr, X_te, y_tr, y_te = train_test_split(
            embeddings, labels,
            test_size=0.4, stratify=labels, random_state=seed
        )
        clf = RandomForestClassifier(n_estimators=100, random_state=seed)
        clf.fit(X_tr, y_tr)
        accs.append(accuracy_score(y_te, clf.predict(X_te)))
    return np.mean(accs), np.std(accs)


